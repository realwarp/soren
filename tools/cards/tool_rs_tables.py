#!/usr/bin/env python3
"""Generate what the Rust calculator (src-tauri/src/calc.rs) shares with the Python pipeline.

    python3 tools/cards/tool_rs_tables.py

Writes, next to calc.rs:
  calc_tables.rs   the unit table, aliases, count nouns and forbidden constants, copied from toolunits.py
  calc.gbnf        the grammar the writer is held to (toolspec.grammar() in the units format)
  calc_vectors.json  cards, asks and units with the answers Python gives, which the Rust tests must reproduce

Run it again whenever toolunits.py or toolspec.py change, then `cargo test calc`.
"""
from __future__ import annotations

import json
import os
import pathlib
import sys

os.environ["TOOL_FORMAT"] = "units"
HERE = pathlib.Path(__file__).parent
sys.path.insert(0, str(HERE))
import toolspec as ts  # noqa: E402
import toolunits as tu  # noqa: E402

SRC = HERE.parent.parent / "src-tauri" / "src"
DATA = HERE.parent.parent / "data" / "cards" / "tool" / "r8data_units.jsonl"


def num(x: float) -> str:
    return repr(float(x))


def tables() -> str:
    out = ["// Generated by tools/cards/tool_rs_tables.py from toolunits.py. Do not edit by hand.", "",
           "/// unit name, exponents over (seconds, bytes, dollars, kilograms, metres), factor to base units",
           "pub(crate) const UNITS: &[(&str, [i32; 5], f64)] = &["]
    for name, (dims, factor) in tu.UNITS.items():
        out.append(f'    ("{name}", [{", ".join(str(d) for d in dims)}], {num(factor)}),')
    out += ["];", "", "pub(crate) const ALIASES: &[(&str, &str)] = &["]
    for k, v in tu.ALIASES.items():
        out.append(f'    ("{k}", "{v}"),')
    out += ["];", "", "pub(crate) const NOUNS: &[&str] = &["]
    out.append("    " + ", ".join(f'"{n}"' for n in sorted(tu.NOUNS)) + ",")
    out += ["];", "", "pub(crate) const FORBIDDEN_CONSTANTS: &[f64] = &[" + ", ".join(num(c) for c in sorted(tu.FORBIDDEN_CONSTANTS)) + "];", ""]
    return "\n".join(out)


def vectors() -> dict:
    rows = [json.loads(line) for line in open(DATA) if line.strip()]
    answerable = [r for r in rows if r["card"].get("decline") is None]
    declines = [r for r in rows if r["card"].get("decline") is not None]
    picked = answerable[:: max(1, len(answerable) // 30)][:30]
    cards = []

    def add(ask: str, card: dict, values: dict | None = None) -> None:
        entry = {"ask": ask, "card": card, "values": values}
        try:
            entry["run"] = ts.run(card, values)
        except Exception:  # noqa: BLE001 - an error is an expected result here
            entry["run"] = None
        try:
            entry["problems"] = ts.problems(card, ask)
        except Exception:  # noqa: BLE001
            entry["problems"] = ["crashed"]
        entry["repaired"] = ts.repair(card) if card.get("decline") is None else card
        cards.append(entry)

    for r in picked:
        c = r["card"]
        add(r["ask"], c)
        first = c["vars"][0]
        add(r["ask"], c, {first["id"]: first["start"] * 0.5 if first["start"] else first["max"]})
        # a card whose answer ignores every slider, a unit that does not fit, a start the ask never gave
        flat = json.loads(json.dumps(c))
        flat["outputs"][0]["formula"] = "1 + 1"
        add(r["ask"], flat)
        wrong = json.loads(json.dumps(c))
        wrong["outputs"][0]["unit"] = "GB" if wrong["outputs"][0]["unit"] != "GB" else "s"
        add(r["ask"], wrong)
        moved = json.loads(json.dumps(c))
        moved["vars"][0]["start"] = moved["vars"][0]["max"]
        moved["vars"][0]["from"] = "message"
        add(r["ask"], moved)
        loose = json.loads(json.dumps(c))
        loose["vars"][0]["start"] = loose["vars"][0]["max"] * 2
        add(r["ask"], loose)
    for r in declines[:6]:
        add(r["ask"], r["card"])

    units = sorted({v.get("unit", "") for r in rows for v in r["card"]["vars"] + r["card"]["outputs"]} | {"per hour", "MB/s", "$/GB-mo", "Gbps", "req/min", "gigz", "/s", "-", "1", "", "%", "¢"})
    unit_rows = [{"unit": u, "dims": list(tu.parse_unit(u)[0]), "factor": tu.parse_unit(u)[1], "loose": tu.parse_unit(u)[2]} for u in units]
    asks = [r["ask"] for r in rows[:300:3]] + ["2.4kg at 3 m/s", "10km in 2h", "5 lakh at 9.5%", "1,000,000 users", "3k and 2.5M and 4b", "about 12 x 4", "100% of 5.",
                                               "8 lakhs, 2 crore and 3 Crores", "12 thousand users", "4 million and 2 mn", "7 lac", "9 billion or 3 bn", "6 cr", "5 lakhly", "2 thousands"]
    nums = [{"ask": a, "numbers": sorted(ts.numbers_in(a))} for a in asks]
    return {"cards": cards, "units": unit_rows, "numbers": nums}


if __name__ == "__main__":
    (SRC / "calc_tables.rs").write_text(tables())
    (SRC / "calc.gbnf").write_text(ts.grammar())
    v = vectors()
    (SRC / "calc_vectors.json").write_text(json.dumps(v, separators=(",", ":")))
    print(f"calc_tables.rs, calc.gbnf, calc_vectors.json: {len(v['cards'])} cards, {len(v['units'])} units, {len(v['numbers'])} asks")
